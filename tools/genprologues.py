#!/usr/bin/env python3
"""Emit the prologue-fingerprint table (src/ql_prologues.inc, read by ql_arm.c)
straight from the binary, for every function address in src/ql_syms.h.

Usage: genprologues.py <qzeroded.x64> > src/ql_prologues.inc"""
import os, re, sys

if len(sys.argv) != 2:
    sys.exit("usage: genprologues.py <qzeroded.x64> > src/ql_prologues.inc")
BIN   = sys.argv[1]
VBASE = 0x400000
N     = 12

# Functions are A_<Capitalised>_name; data is A_<lowercase> and is not fingerprinted.
hdr = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "ql_syms.h")).read()
syms = re.findall(r"^#define (A_[A-Z][A-Za-z0-9]*_\w+)\s+(0x[0-9a-f]+)",
                  hdr, re.M)

blob = open(BIN, "rb").read()
print("/* GENERATED by tools/genprologues.py -- do not edit by hand. */")
print("static const ql_prologue_t ql_prologues[] = {")
for name, addr in syms:
    a = int(addr, 16)
    b = blob[a - VBASE:a - VBASE + N]
    if len(b) != N:
        sys.exit("short read at %s" % name)
    print('\t{ "%s", %s, { %s } },'
          % (name[2:], addr, ", ".join("0x%02x" % x for x in b)))
print("};")
